'use strict';
/*
 * Writes the grids of tools/les-familles/data.js into games/les-familles/index.html, between the
 * GRIDS markers (names and words only: the word table stays out of the game).
 *   node tools/les-familles/build.js
 */
const fs = require('node:fs');
const path = require('node:path');
const { TAGS, GRIDS } = require('./data');

const FILE = path.join(__dirname, '..', '..', 'games', 'les-familles', 'index.html');

function embedded() {
  return GRIDS.map(g => g.map(([t, ws]) => [TAGS[t], ws]));
}
function block() {
  return '/*GRIDS:BEGIN (generated by tools/les-familles/build.js, do not edit by hand)*/\n' +
    'var GRIDS=[\n' + embedded().map(g => '  ' + JSON.stringify(g)).join(',\n') + '\n];\n/*GRIDS:END*/';
}
module.exports = { embedded, block };

if (require.main === module) {
  const html = fs.readFileSync(FILE, 'utf8');
  const re = /\/\*GRIDS:BEGIN[\s\S]*?\/\*GRIDS:END\*\//;
  if (!re.test(html)) throw new Error('GRIDS markers not found');
  fs.writeFileSync(FILE, html.replace(re, () => block()));
  console.log('grids written to ' + FILE);
}
