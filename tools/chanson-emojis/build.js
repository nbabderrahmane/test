'use strict';
/*
 * Builds the data block of games/chanson-emojis/index.html and docs/contenu/chanson-emojis.md
 * from tools/chanson-emojis/devinettes.json (the single source of the content).
 * Order in the file = order of play: 3 riddles per level, 20 levels.
 * Usage: node tools/chanson-emojis/build.js
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(__dirname, 'devinettes.json');
const HTML = path.join(ROOT, 'games', 'chanson-emojis', 'index.html');
const DOC = path.join(ROOT, 'docs', 'contenu', 'chanson-emojis.md');

const list = JSON.parse(fs.readFileSync(SRC, 'utf8'));
if (list.length !== 60) throw new Error('60 riddles expected, got ' + list.length);
const titles = new Set(list.map(x => x.t));
if (titles.size !== 60) throw new Error('duplicate title');
list.forEach(x => {
  if (x.e.split(' ').length > 4) throw new Error('too many emojis: ' + x.t);
  if (!['A', 'M'].includes(x.g)) throw new Error('bad group: ' + x.t);
});

const decade = y => Math.floor(y / 10) * 10;
const rows = list.map(x => [x.e, x.t, x.a, x.h ? 0 : decade(x.y), x.g]);   // decade 0 = not shown in the hint
const block = '/*DATA:BEGIN (generated by tools/chanson-emojis/build.js, do not edit by hand)*/\nvar DATA=' +
  JSON.stringify(rows).replace(/\],\[/g, '],\n[') + ';\n/*DATA:END*/';
let html = fs.readFileSync(HTML, 'utf8');
html = html.replace(/\/\*DATA:BEGIN[\s\S]*?\/\*DATA:END\*\//, () => block);
fs.writeFileSync(HTML, html);

const dl = y => y >= 2000 ? 'années ' + y : 'années ' + (y % 100);
const count = f => list.filter(f).length;
let md = '# Fredonne (`chanson-emojis`) : contenu\n\n';
md += '**À valider par un humain avant publication.**\n\n';
md += 'Source unique : `tools/chanson-emojis/devinettes.json`. Ce fichier est généré par `node tools/chanson-emojis/build.js`.\n\n';
md += 'Règles suivies : titres et noms d\'artistes seulement (ni paroles, ni pochette, ni extrait) ; les emojis évoquent le titre ; seuls des emojis anciens et courants sont utilisés (pas de séquence composée, pas de drapeau, pas de teinte de peau) ; ';
md += 'rien d\'explicite, de violent, de politique ou de religieux. La « certitude » est mon propre degré de confiance sur le titre, l\'artiste et la date ; elle ne remplace pas la vérification humaine.\n\n';
md += 'Chaque niveau compte 3 devinettes dans l\'ordre ci-dessous. Les 3 mauvaises réponses de chaque devinette sont tirées au sort (graine) parmi les autres titres du même groupe (A ou M) qui ne sont pas dans le même niveau. Quand la décennie est discutable, l\'indice ne montre que l\'artiste.\n\n';
md += '## Répartition\n\n';
md += `- Groupe A (titres africains ou francophones) : ${count(x => x.g === 'A')}, répartis sur les 19 premiers niveaux (2 par niveau).\n`;
md += `- Groupe M (succès mondiaux) : ${count(x => x.g === 'M')}, 1 par niveau sur les niveaux 1 à 19, puis le niveau 20 en entier.\n`;
const AFR = ['Pata Pata', 'Soul Makossa', '7 Seconds', 'Sodade', 'Premier Gaou', 'Magic in the Air', 'Grazing in the Grass', 'Weekend Special', "Parce qu'on vient de loin"];
md += `- Dont artistes africains ou nés en Afrique (${AFR.length}) : ${AFR.join(', ')}. Les autres titres du groupe A sont francophones (France, Belgique, Canada) et connus en Afrique francophone.\n`;
md += '- Par décennie : ' + [...new Set(list.map(x => decade(x.y)))].sort().map(d => `${d} : ${count(x => decade(x.y) === d)}`).join(' · ') + '.\n\n';
md += '## Devinettes\n\n';
md += '| Niv. | N° | Emojis | Titre | Artiste | Année | Décennie affichée (indice) | Région | Certitude | Remarque |\n|---|---|---|---|---|---|---|---|---|---|\n';
list.forEach((x, i) => {
  md += `| ${Math.floor(i / 3) + 1} | ${i % 3 + 1} | ${x.e} | ${x.t} | ${x.a} | ${x.y} | ${x.h ? '(non affichée)' : dl(decade(x.y))} | ${x.r} | ${x.c} | ${x.n || ''} |\n`;
});
md += '\n## À regarder en priorité\n\n';
list.filter(x => x.c !== 'Très élevée').forEach(x => { md += `- ${x.t} (${x.a}) : certitude ${x.c.toLowerCase()}. ${x.n}\n`; });
fs.writeFileSync(DOC, md);
console.log('ok: ' + rows.length + ' riddles');
