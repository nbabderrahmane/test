'use strict';
// Builds the data block of games/cap-sur/index.html and docs/contenu/cap-sur.md
// from tools/cap-sur/cities.txt and tools/cap-sur/levels.txt.
// Usage: node tools/cap-sur/build.js
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', '..');
const read = f => fs.readFileSync(path.join(__dirname, f), 'utf8').split('\n').filter(l => l.trim() && l[0] !== '#');

const cities = read('cities.txt').map(l => {
  const [name, country, lat, lon, flag] = l.split('|');
  return { name, country, lat: +lat, lon: +lon, latS: lat, lonS: lon, cap: flag === 'c' };
});
const names = cities.map(c => c.name);
if (new Set(names).size !== names.length) throw new Error('duplicate city names');
cities.forEach(c => {
  if (!(c.lat >= -35.5 && c.lat <= 37.5 && c.lon >= -26 && c.lon <= 58)) throw new Error('out of Africa: ' + c.name);
});
const levels = read('levels.txt').map(l => { const [n, name] = l.split('|'); return { n: +n, name }; });
if (levels.length !== 20) throw new Error('need 20 levels');
levels.forEach((l, i) => {
  if (l.n !== i + 1) throw new Error('level order');
  const k = names.indexOf(l.name);
  if (k < 0) throw new Error('unknown target ' + l.name);
  if (i < 8 && !cities[k].cap) throw new Error('levels 1-8 must be capitals: ' + l.name);
  l.idx = k; l.city = cities[k];
});
if (new Set(levels.map(l => l.idx)).size !== 20) throw new Error('repeated target');

// game file
const file = path.join(ROOT, 'games', 'cap-sur', 'index.html');
const block = '/*DATA:BEGIN (generated by tools/cap-sur/build.js, do not edit by hand)*/\n' +
  'var CITIES = [\n' + cities.map(c => '  ' + JSON.stringify([c.name, c.country, c.latS, c.lonS].join('|') + (c.cap ? '|c' : ''))).join(',\n') + '\n];\n' +
  'var TARGETS = ' + JSON.stringify(levels.map(l => l.idx)) + ';\n' +
  '/*DATA:END*/';
const html = fs.readFileSync(file, 'utf8');
const out = html.replace(/\/\*DATA:BEGIN[\s\S]*?\/\*DATA:END\*\//, () => block);
if (out === html && !html.includes(block)) throw new Error('markers not found');
fs.writeFileSync(file, out);

// content sheet for human validation
const md = [
  '# cap-sur (Girouette) : contenu',
  '',
  '> **À valider par un humain avant publication.** Les coordonnées ont été écrites de mémoire (une décimale, soit ~10 km de précision ; deux décimales pour Kinshasa et Brazzaville, très proches) et n\'ont été vérifiées contre aucune source externe.',
  '',
  'Source de vérité : `tools/cap-sur/cities.txt` et `tools/cap-sur/levels.txt` ; `node tools/cap-sur/build.js` régénère le jeu et cette fiche.',
  '',
  '## Règles de contenu',
  '',
  '- ' + cities.length + ' villes d\'Afrique, avec pays, latitude et longitude (degrés décimaux, une décimale ; deux pour Kinshasa et Brazzaville).',
  '- Aucune ville de territoire au statut disputé. Aucune ville de territoire d\'outre-mer d\'un autre continent.',
  '- Statut de capitale : seules les capitales au statut stable sont marquées (Malabo, dont le siège du gouvernement est en cours de transfert, ne l\'est pas ; Gitega n\'est pas proposée).',
  '- Aucune paire de villes à moins de 5 km (Kinshasa et Brazzaville : deux décimales). Si la distance arrondie est inférieure à 10 km sans être la bonne ville, le jeu affiche « moins de 10 km ».',
  '- Pas de carte, pas de frontière dessinée. Noms de pays en français d\'usage courant.',
  '- Distance : formule de haversine (rayon 6371 km), arrondie au km. Direction : 8 flèches (nord, nord-est, est, sud-est, sud, sud-ouest, ouest, nord-ouest) depuis la ville proposée vers la ville à trouver.',
  '- Proximité : 100 % si c\'est la bonne ville, sinon `100 × (1 − distance / 9000 km)` arrondi, borné à 0-99 %.',
  '',
  '## Les 20 niveaux (question : « Quelle est cette ville ? » ; réponse)',
  '',
  '| Niveau | Réponse | Pays | Type | Latitude | Longitude |',
  '|---|---|---|---|---|---|',
  ...levels.map(l => `| ${l.n} | ${l.city.name} | ${l.city.country} | ${l.n <= 8 ? 'capitale' : 'grande ville'} | ${l.city.latS} | ${l.city.lonS} |`),
  '',
  '## Les ' + cities.length + ' villes proposées (saisie et suggestions)',
  '',
  '| Ville | Pays | Latitude | Longitude | Capitale |',
  '|---|---|---|---|---|',
  ...cities.map(c => `| ${c.name} | ${c.country} | ${c.latS} | ${c.lonS} | ${c.cap ? 'oui' : ''} |`),
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'docs', 'contenu', 'cap-sur.md'), md);
console.log('cities:', cities.length, '| levels:', levels.length, '| html bytes:', fs.statSync(file).size);
