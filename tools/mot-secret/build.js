'use strict';
/*
 * Mot Tapi build tool (node tools/mot-secret/build.js).
 *  - reads tools/mot-secret/mots.txt (admitted words) and the 20 answers below;
 *  - strips accents, keeps 4..7 letters a-z, de-duplicates, sorts;
 *  - writes tools/mot-secret/niveaux.json (answers, for the tests and the content doc);
 *  - writes tools/mot-secret/mots-admis.txt (the final admitted list, one per line);
 *  - patches the data block of games/mot-secret/index.html (between the DATA markers).
 * Answers are stored lightly encoded in the game (not shown to the casual reader of the source).
 */
const fs = require('node:fs');
const path = require('node:path');

// The 20 levels: [answer, one-line reason it is easy or hard]. Lengths: 4 (1-5), 5 (6-11), 6 (12-16), 7 (17-20).
const ANSWERS = [
  'chat', 'lune', 'pain', 'soif', 'exil',
  'table', 'plage', 'fleur', 'nuage', 'arbre', 'etang',
  'bateau', 'jardin', 'miroir', 'chemin', 'tunnel',
  'cuisine', 'chapeau', 'musique', 'mystere',
];
const ROOT = path.join(__dirname, '..', '..');
const norm = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/œ/g, 'oe').replace(/æ/g, 'ae').toLowerCase();

const raw = fs.readFileSync(path.join(__dirname, 'mots.txt'), 'utf8');
const set = new Set();
let dropped = 0;
raw.split('\n').forEach(l => {
  if (l.startsWith('#')) return;
  l.split(/\s+/).filter(Boolean).forEach(w => {
    const n = norm(w);
    if (/^[a-z]{4,7}$/.test(n)) set.add(n); else dropped++;
  });
});
ANSWERS.forEach(a => set.add(a));   // an answer must always be admitted
const words = [...set].sort();
const byLen = { 4: [], 5: [], 6: [], 7: [] };
words.forEach(w => byLen[w.length].push(w));
fs.writeFileSync(path.join(__dirname, 'mots-admis.txt'), words.join('\n') + '\n');
fs.writeFileSync(path.join(__dirname, 'niveaux.json'), JSON.stringify({ answers: ANSWERS }, null, 1) + '\n');

// Light encoding of an answer (reverse + position-dependent shift). Decoded by the game at boot.
const enc = w => w.split('').map((c, i) => String.fromCharCode((c.charCodeAt(0) - 97 + 7 + i * 3) % 26 + 97)).reverse().join('');
const data = '/*DATA:BEGIN (generated by tools/mot-secret/build.js, do not edit by hand)*/\n' +
  'var ANS="' + ANSWERS.map(enc).join(' ') + '";\n' +
  'var DICT={' + [4, 5, 6, 7].map(n => n + ':"' + byLen[n].join('') + '"').join(',') + '};\n' +
  '/*DATA:END*/';
const file = path.join(ROOT, 'games', 'mot-secret', 'index.html');
if (fs.existsSync(file)) {
  let html = fs.readFileSync(file, 'utf8');
  const re = /\/\*DATA:BEGIN[\s\S]*?\/\*DATA:END\*\//;
  if (!re.test(html)) throw new Error('DATA markers not found');
  html = html.replace(re, () => data);
  fs.writeFileSync(file, html);
}
console.log('admitted words: ' + words.length + ' (' + [4, 5, 6, 7].map(n => n + ':' + byLen[n].length).join(' ') + '), dropped (length/charset): ' + dropped);
